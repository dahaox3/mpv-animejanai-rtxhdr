#!/usr/bin/env python3
"""Embed the bridge PTX; nvcc is needed only when regenerating this header."""
import argparse
import json
import pathlib
import subprocess
import tempfile

args = argparse.ArgumentParser()
args.add_argument('--nvcc', default='nvcc')
args.add_argument('--allow-unsupported-compiler', action='store_true')
opts = args.parse_args()
root = pathlib.Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory() as tmp:
    ptx = pathlib.Path(tmp) / 'bridge.ptx'
    cmd = [opts.nvcc, '--ptx', '--gpu-architecture=compute_75',
           str(root / 'video/filter/cuda_d3d11.cu'), '-o', str(ptx)]
    if opts.allow_unsupported_compiler:
        cmd.append('--allow-unsupported-compiler')
    subprocess.run(cmd, check=True)
    text = ptx.read_text(encoding='utf-8')
    body = ''.join(json.dumps(line + '\n') + '\n' for line in text.splitlines())
    target = root / 'video/filter/cuda_d3d11_ptx.h'
    target.write_text('/* SPDX-License-Identifier: LGPL-2.1-or-later\n'
                      ' * Generated by TOOLS/cuda_d3d11_ptx.py. */\n'
                      'static const char cuda_d3d11_ptx[] =\n' + body + ';\n',
                      encoding='utf-8', newline='\n')
